"""Timeline ViewModel — unified row + selection + state data layer.

This is the P1 shared data layer for the AE-style timeline (per
``docs/composite_ae_like_timeline_implementation_plan_2026-08-06.md`` §5.2
and tasks T04, T07-T14).

Design rules (enforced by the unit tests in
``tests/composite/test_timeline_view_model.py``):

1. **GUI-free.** This module imports no QWidget / QPainter / QColor. It is
   pure data + a lightweight observable selection model, so it can be
   unit-tested headlessly and queried by AI/script.
2. **Stable row_id scheme (T04).** Row ids are human-inspectable strings
   that are *stable across rebuilds* for the same node instance + parameter,
   and *reversible* via :func:`parse_row_id`:

       node row        → ``node:{node_id}``
       group row       → ``group:{node_id}:{group_name}``
       parameter row   → ``param:{node_id}:{param_name}``
       channel row     → ``channel:{node_id}:{param_name}:{channel}``
       expression row  → ``expr:{node_id}:{param_name}``

   The legacy :class:`KeyframesModel` already emits ``node:`` and ``param:``
   ids, so :func:`build_timeline_rows` reuses them verbatim to keep the 216
   existing UI tests green (T10/T14 compat).
3. **The adapter is additive.** :class:`KeyframesRow` / KeyframePointVisual
   remain the source-of-truth render structures the views paint today;
   :class:`TimelineRow` is a parallel, richer projection that the Spline
   panel, AI, and the upcoming Graph Editor consume. Views migrate to read
   it directly in P3.
4. **Selection is shared and observable.** :class:`AnimationSelectionModel`
   is the single object both Keyframes and Spline subscribe to (T08/T13).
   It mirrors its state onto the legacy per-point ``selected`` flags via
   :meth:`apply_to_model`, so existing view code keeps working while new
   surfaces read the unified selection.

The dataclasses here intentionally carry fields the current single-scalar
codebase does not yet populate (``channels``, ``has_expression`` for the
param row, group/channel row types). They are reserved for P3+ so that the
data contract does not churn every phase.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Set, Tuple

# Row id prefixes — centralised so every caller spells them identically.
ROW_NODE = "node"
ROW_GROUP = "group"
ROW_PARAM = "param"
ROW_CHANNEL = "channel"
ROW_EXPRESSION = "expr"


# ── row_id construction / parsing (T04) ─────────────────────────────────


def make_node_row_id(node_id: str) -> str:
    return f"{ROW_NODE}:{node_id}"


def make_group_row_id(node_id: str, group_name: str) -> str:
    return f"{ROW_GROUP}:{node_id}:{group_name}"


def make_param_row_id(node_id: str, param_name: str) -> str:
    return f"{ROW_PARAM}:{node_id}:{param_name}"


def make_channel_row_id(node_id: str, param_name: str, channel: str) -> str:
    return f"{ROW_CHANNEL}:{node_id}:{param_name}:{channel}"


def make_expression_row_id(node_id: str, param_name: str) -> str:
    return f"{ROW_EXPRESSION}:{node_id}:{param_name}"


def parse_row_id(row_id: str) -> Dict[str, Any]:
    """Reverse of the ``make_*_row_id`` helpers.

    Returns a dict with ``row_type`` plus the components, e.g.::

        {"row_type": "param", "node_id": "ab12", "param_name": "rotation"}

    Unknown / malformed ids round-trip as ``{"row_type": "unknown",
    "row_id": row_id}`` so callers can pass anything through without raising.
    """
    if not isinstance(row_id, str) or ":" not in row_id:
        return {"row_type": "unknown", "row_id": row_id}
    prefix, _, rest = row_id.partition(":")
    parts = rest.split(":") if rest else []
    if prefix == ROW_NODE and len(parts) >= 1:
        return {"row_type": ROW_NODE, "node_id": parts[0]}
    if prefix == ROW_GROUP and len(parts) >= 2:
        return {"row_type": ROW_GROUP, "node_id": parts[0],
                "group_name": parts[1]}
    if prefix == ROW_PARAM and len(parts) >= 2:
        return {"row_type": ROW_PARAM, "node_id": parts[0],
                "param_name": parts[1]}
    if prefix == ROW_CHANNEL and len(parts) >= 3:
        return {"row_type": ROW_CHANNEL, "node_id": parts[0],
                "param_name": parts[1], "channel": parts[2]}
    if prefix == ROW_EXPRESSION and len(parts) >= 2:
        return {"row_type": ROW_EXPRESSION, "node_id": parts[0],
                "param_name": parts[1]}
    return {"row_type": "unknown", "row_id": row_id}


# ── TimelineRow (T07) ───────────────────────────────────────────────────


@dataclass
class TimelineRow:
    """One row in the unified timeline (node / group / parameter / channel /
    expression).

    Pure data — no QWidget/QPainter. Generated by :func:`build_timeline_rows`
    from the legacy :class:`KeyframesModel`, or directly by future code paths
    (Graph Editor, AI queries).
    """

    row_id: str
    node_id: str
    row_type: str
    display_name: str
    depth: int = 0
    parent_row_id: Optional[str] = None
    parameter_name: Optional[str] = None
    group_name: Optional[str] = None
    channel: Optional[str] = None
    color: str = "#555555"
    locked: bool = False
    visible: bool = True
    expanded: bool = True
    is_animated: bool = False
    has_expression: bool = False
    expression_enabled: bool = True
    expression_error: Optional[str] = None
    current_value: Any = None
    channels: Tuple[str, ...] = field(default_factory=tuple)
    # Internal flag set by the adapter: True for node rows whose children are
    # currently visible (expanded). Consumers should prefer ``expanded``.
    selected: bool = False

    @property
    def is_node(self) -> bool:
        return self.row_type == ROW_NODE

    @property
    def is_parameter(self) -> bool:
        return self.row_type == ROW_PARAM

    @property
    def is_expression(self) -> bool:
        return self.row_type == ROW_EXPRESSION

    @property
    def is_channel(self) -> bool:
        return self.row_type == ROW_CHANNEL

    @property
    def is_group(self) -> bool:
        return self.row_type == ROW_GROUP


# ── AnimationSelection (T08) ────────────────────────────────────────────


@dataclass(frozen=False)
class AnimationSelection:
    """Cross-panel selection snapshot.

    ``keyframes`` is a set of ``(row_id, frame)`` pairs so selection spans
    multiple parameter tracks (AE-style multi-keyframe drag). ``rows`` is the
    set of selected left-tree rows (node / parameter). Exactly one of
    ``primary_*`` may be set to mark the anchor keyframe / row for navigation
    (``J/K``, copy/paste anchoring, Spline focus).
    """

    keyframes: Set[Tuple[str, int]] = field(default_factory=set)
    rows: Set[str] = field(default_factory=set)
    primary_row_id: Optional[str] = None
    primary_frame: Optional[int] = None

    def clear(self) -> None:
        self.keyframes.clear()
        self.rows.clear()
        self.primary_row_id = None
        self.primary_frame = None

    def is_empty(self) -> bool:
        return not self.keyframes and not self.rows

    def keyframes_for_row(self, row_id: str) -> List[int]:
        """Frames of selected keyframes on ``row_id``, ascending."""
        return sorted(f for rid, f in self.keyframes if rid == row_id)

    def keyframe_count(self) -> int:
        return len(self.keyframes)

    def clone(self) -> "AnimationSelection":
        return AnimationSelection(
            keyframes=set(self.keyframes),
            rows=set(self.rows),
            primary_row_id=self.primary_row_id,
            primary_frame=self.primary_frame,
        )


