# Test 2 (B5): Reasoning-model empty-reply auto-retry
# --------------------------------------------------------------------------- #


def test_b5_reasoning_retry(
    registry: ProfileRegistry, store: HybridCredentialStore
) -> None:
    _banner("测试 2 (B5) · Reasoning 模型空回复自动重试")

    # Find a reasoning model (glm-5.x or deepseek-v4-flash).
    reasoning_profile = None
    for p in registry._profiles.values():
        model = (p.model_id or "").lower()
        if model.startswith("glm-5") or "deepseek-v4-flash" in model:
            reasoning_profile = p
            break
    if reasoning_profile is None:
        _record("B5 reasoning retry", False, "无 reasoning 模型（需要 glm-5.x 或 deepseek-v4-flash）")
        return

    client = make_client(reasoning_profile, store)
    if client is None:
        _record("B5 reasoning retry", False, "make_client 返回 None")
        return

    # Step 1: with a tiny max_tokens, the reasoning channel eats the budget.
    # The client should auto-retry with thinking disabled and still return text.
    prompt = "请详细解释伽马校正的原理，至少 200 字。"
    messages = [{"role": "user", "content": prompt}]

    t0 = time.perf_counter()
    try:
        # max_tokens=128 is deliberately tiny: reasoning models burn it all on
        # internal thinking → finish_reason=length, content="".  The retry path
        # in OpenAICompatClient.complete should detect this and retry with
        # thinking disabled.
        reply = client.complete(messages, temperature=0.6, max_tokens=128)
        elapsed = time.perf_counter() - t0
        ok = bool(reply and reply.strip())
        detail = f"{len(reply or '')}字符 {elapsed:.1f}s"
        if ok:
            detail += f" | 重试成功，回复: {(reply or '').strip()[:80]!r}"
        else:
            detail += " | 空回复（重试未生效？）"
        _record(f"B5·{reasoning_profile.model_id} 小 max_tokens 重试", ok, detail)
    except Exception as exc:  # noqa: BLE001
        _record(f"B5·{reasoning_profile.model_id} 小 max_tokens 重试", False,
                f"{type(exc).__name__}: {exc}")

    # Step 2: normal-sized call — should succeed without needing the retry.
    t0 = time.perf_counter()
    try:
        reply = client.complete(messages, temperature=0.6, max_tokens=4096)
        elapsed = time.perf_counter() - t0
        ok = bool(reply and reply.strip())
        _record(f"B5·{reasoning_profile.model_id} 正常 max_tokens", ok,
                f"{len(reply or '')}字符 {elapsed:.1f}s")
    except Exception as exc:  # noqa: BLE001
        _record(f"B5·{reasoning_profile.model_id} 正常 max_tokens", False,
                f"{type(exc).__name__}: {exc}")


