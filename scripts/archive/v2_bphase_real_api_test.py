def _load_profiles() -> tuple[ProfileRegistry, HybridCredentialStore]:
    store = HybridCredentialStore(prefer="file")
    registry = ProfileRegistry()
    if not registry.load_from_user_file():
        print("无法加载 ~/.topos/ai_profiles.json，终止。")
        sys.exit(2)
    return registry, store


def _find_profile(registry: ProfileRegistry, *, provider_kind: str):
    for p in registry._profiles.values():
        if p.provider_kind == provider_kind:
            return p
    return None


def _find_profiles_by_capability(registry: ProfileRegistry, capability: str):
    out = []
    for p in registry._profiles.values():
        caps = getattr(p, "capabilities", ()) or ()
        if capability in caps:
            out.append(p)
    return out


