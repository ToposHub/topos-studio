# Test 1: Profile sweep — every language profile answers one prompt
# --------------------------------------------------------------------------- #


def test_profile_sweep(registry: ProfileRegistry, store: HybridCredentialStore) -> None:
    _banner("测试 1 · 全语言 Profile 扫描")
    lang_profiles = _find_profiles_by_capability(registry, "language")
    if not lang_profiles:
        _record("Profile 扫描", False, "无 language capability profile")
        return

    prompt = "用一句话告诉我，什么是色温（color temperature）？"
    messages = [{"role": "user", "content": prompt}]

    for profile in lang_profiles:
        label = f"Profile·{profile.display_name} ({profile.model_id})"
        t0 = time.perf_counter()
        try:
            client = make_client(profile, store)
            if client is None:
                _record(label, False, "make_client 返回 None")
                continue
            reply = client.complete(messages, temperature=0.4, max_tokens=4096)
            elapsed = time.perf_counter() - t0
            usage = getattr(client, "last_usage", None)
            reply_preview = (reply or "").strip().replace("\n", " ")[:100]
            ok = bool(reply and reply.strip())
            detail = f"{len(reply)}字符 {elapsed:.1f}s | {reply_preview!r}"
            if usage:
                ap = getattr(usage, "prompt_tokens", None)
                ac = getattr(usage, "completion_tokens", None)
                detail += f" | tok={ap}+{ac}"
            _record(label, ok, detail)
        except Exception as exc:  # noqa: BLE001
            _record(label, False, f"{type(exc).__name__}: {exc}")


