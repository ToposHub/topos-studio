def test_b7_image_agentrun(
    registry: ProfileRegistry, store: HybridCredentialStore
) -> None:
    _banner("测试 6a (B7) · 图片生成统一 AgentRun 事件流")

    seedream = _find_profile(registry, provider_kind="volcengine_seedream")
    if seedream is None:
        _record("B7 image AgentRun", False, "无 volcengine_seedream profile")
        return

    provider = make_volcengine_generation_provider(seedream, store)
    if provider is None:
        _record("B7 image AgentRun", False, "make_volcengine_generation_provider 返回 None")
        return

    orch = AgentOrchestrator()

    # Mirror the controller's _v2_track_media_generation flow.
    runtime_run_id = f"rt-img-{uuid.uuid4().hex[:8]}"
    task = AgentTask(
        task_id=f"media-{runtime_run_id}",
        session_id="media",
        title="AI image 生成",
        user_goal="",
        kind="image",
    )
    v2_run_id = orch.start_task(task, mode="image")
    orch.mark_context_ready(v2_run_id)
    orch.mark_plan_ready(v2_run_id)

    # Actual generation.
    req = GenerationRequest(
        request_id=f"img-{uuid.uuid4().hex[:8]}",
        modality=GenerationModality.IMAGE,
        prompt="电影感日落风景：金色光线洒在海面上，远处有灯塔，暖色调，广角镜头",
        consent=GenerationConsent(confirmed=True, provider_id=seedream.profile_id),
        budget=GenerationBudget(max_candidates=1),
    )
    t0 = time.perf_counter()
    try:
        result = provider.generate(req)
    except Exception as exc:  # noqa: BLE001
        orch.fail(v2_run_id, reason=str(exc))
        _record("B7·图片生成", False, f"{type(exc).__name__}: {exc}")
        return
    elapsed = time.perf_counter() - t0

    ok_gen = bool(result.candidates) and not result.error_code
    detail = f"{len(result.candidates)} 张 {elapsed:.1f}s"
    if result.candidates:
        detail += f" | preview_handle={str(result.candidates[0].preview_handle)[:60]}..."
    _record("B7·Seedream 图片生成", ok_gen, detail)

    if not ok_gen:
        orch.fail(v2_run_id, reason=result.error_code or "生成失败")
        return

    # B7: stage artifact.
    from src.features.edit.ai_editing.agent_models import (
        ArtifactKind, ArtifactRef,
    )
    artifact = ArtifactRef(
        artifact_id=f"media-{runtime_run_id}",
        kind=ArtifactKind.IMAGE,
        location=str(result.candidates[0].preview_handle),
        created_at=time.time(),
    )
    orch.stage_artifact(v2_run_id, artifact)

    # B7: complete.
    orch.begin_verification(v2_run_id)
    orch.finish_verification(v2_run_id, success=True)

    run = orch.get_run(v2_run_id)
    events = [e.kind for e in orch.get_events(v2_run_id)]
    ok_flow = (
        run is not None
        and run.state == AgentRunState.SUCCEEDED
        and AgentEventKind.ARTIFACT_STAGED in events
        and AgentEventKind.RUN_COMPLETED in events
    )
    _record("B7·图片 AgentRun (stage+complete)", ok_flow,
            f"state={run.state if run else 'MISSING'} events={len(events)}")


