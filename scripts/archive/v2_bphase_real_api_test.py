#!/usr/bin/env python3
"""B-phase real-API integration test (B3 / B4 / B5 / B6 / B7).

The two earlier smoke scripts (``v2_real_chat_smoke.py`` and
``v2_real_multimode_smoke.py``) validate the *base* V2 pipeline: chat through
``ChatRunDriver``, Motion Graphic HTML, image and TTS via direct provider calls.

This script exercises the features added by the **B-phase** commits that those
scripts predate — features that only become visible when you compose the
orchestrator, coordinator and persistence layers the way the real controller
does:

- **B3** — Motion Graphic **full AgentRun lifecycle**: ``MotionGraphicRunCoordinator``
  ``start_build → stage_html → record_verification → request_confirmation →
  confirm_and_write → complete_write``, with the real HTML generated by the
  language model and a real artifact hash.
- **B5** — Reasoning-model **empty-reply auto-retry**: call ``client.complete``
  with a deliberately tiny ``max_tokens`` so the reasoning channel exhausts the
  budget (``finish_reason=length``, empty content); the client must retry once
  with thinking disabled and return a non-empty reply.
- **B6** — History **full-text storage**: take a real model reply, persist it
  through ``MessageRecord`` and verify the body is **not** truncated at the old
  500-char cap.
- **B4** — Checkpoint **persist / restore round-trip**: after a real run, export
  orchestrator state, write to a temp file, read it back and restore into a
  fresh orchestrator; the run must reappear and remain queryable.
- **B7** — Media generation **unified AgentRun event stream**: run a real
  Seedream image generation and a real Doubao TTS call, but — unlike the old
  multimode script — mirror the controller's ``_v2_track_media_generation``
  flow so each media job also creates a V2 ``AgentRun`` with
  ``artifact.staged`` + ``RUN_COMPLETED`` events.
- **Profile sweep** — every configured language profile (glm-5.2, DeepSeek-v4-
  flash, DeepSeek-v4-pro, doubao-seed-2.0-lite) answers the same prompt so we
  know no provider is silently broken.

Run::

    PYTHONPATH=$(pwd) PYTHONUNBUFFERED=1 .venv/bin/python -u scripts/v2_bphase_real_api_test.py
"""

