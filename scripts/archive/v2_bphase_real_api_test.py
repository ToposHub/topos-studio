# Test 5 (B3): Motion Graphic full AgentRun lifecycle
# --------------------------------------------------------------------------- #


def test_b3_motion_graphic_agentrun(
    registry: ProfileRegistry, store: HybridCredentialStore
) -> None:
    _banner("测试 5 (B3) · Motion Graphic 完整 AgentRun 生命周期")

    active = registry.active_profile
    client = make_client(active, store)
    if client is None:
        _record("B3 MG AgentRun", False, "make_client 返回 None")
        return

    orch = AgentOrchestrator()
    coord = MotionGraphicRunCoordinator(orch)

    # Step 1: start_build — creates the AgentRun.
    task_id = f"mg-{uuid.uuid4().hex[:8]}"
    fingerprint = hashlib.sha256(b"test-scene-v1").hexdigest()[:16]
    request = MotionGraphicBuildRequest(
        task_id=task_id,
        user_brief="6 秒科技标题卡：大标题 + 副标题 + CSS keyframe 动画入场",
        scene_revision=0,
        context_fingerprint=fingerprint,
        canvas_width=1920,
        canvas_height=1080,
    )
    run_id = coord.start_build(request)
    run = orch.get_run(run_id)
    ok_start = run is not None and run.state in (
        AgentRunState.GATHERING_CONTEXT, AgentRunState.CREATED,
    )
    _record("B3·start_build 创建 run", ok_start,
            f"run_id={run_id[:12]} state={run.state if run else 'MISSING'}")

    # Step 2: generate real HTML via the model.
    constraints = HtmlGenerationConstraints(
        viewport_width=1920, viewport_height=1080, page_count=1,
    )
    llm_request = LlmGenerationRequest(
        user_prompt=(
            "Create a 6-second dark tech title card. Big title 'TOPOS COLOR', "
            "subtitle 'Professional Color Grading', with a CSS keyframe entrance. "
            "1920x1080, single page."
        ),
        temperature=0.4,
        max_tokens=6000,
    )
    t0 = time.perf_counter()
    try:
        html = generate_raw_html(client, llm_request, constraints=constraints)
    except Exception as exc:  # noqa: BLE001
        _record("B3·HTML 生成", False, f"{type(exc).__name__}: {exc}")
        coord.fail(run_id, reason=str(exc))
        return
    elapsed = time.perf_counter() - t0

    has_doctype = "<!doctype" in html.lower() or "<!DOCTYPE" in html
    has_style = "<style" in html.lower()
    has_keyframes = "@keyframes" in html
    ok_html = bool(html and html.strip()) and has_doctype and has_keyframes
    detail = f"{len(html)}字符 {elapsed:.1f}s | DOCTYPE={has_doctype} keyframes={has_keyframes}"
    _record("B3·generate_raw_html", ok_html, detail)

    if not ok_html:
        coord.fail(run_id, reason="HTML 质量检查未通过")
        return

    # Step 3: stage_html — emit artifact.staged + run.verification_started.
    raw_hash = hashlib.sha256(html.encode()).hexdigest()
    sanitized_hash = hashlib.sha256(html.encode()).hexdigest()
    artifact = coord.stage_html(
        run_id,
        raw_html_hash=raw_hash,
        sanitized_html_hash=sanitized_hash,
        html_payload_ref=f"artifact://{task_id}/page-1.html",
        page_count=1,
        viewport=(1920, 1080),
    )
    events_after_stage = [e.kind for e in orch.get_events(run_id)]
    ok_stage = (
        AgentEventKind.ARTIFACT_STAGED in events_after_stage
        and artifact.is_staged
    )
    _record("B3·stage_html (artifact.staged)", ok_stage,
            f"events={' → '.join(events_after_stage[-4:])}")

    # Step 4: record_verification — attach render evidence.
    artifact = coord.record_verification(
        run_id, artifact,
        render_evidence={"backend": "headless", "frames_captured": 10,
                         "deterministic": True},
        quality_report={"score": 0.95, "issues": []},
        sanitizer_version="v2.1",
    )
    events_after_verify = [e.kind for e in orch.get_events(run_id)]
    ok_verify = (
        AgentEventKind.RUN_VERIFICATION_FINISHED in events_after_verify
        and artifact.has_verification_evidence
    )
    _record("B3·record_verification", ok_verify,
            f"has_evidence={artifact.has_verification_evidence}")

    # Step 5: request_confirmation → WAITING_APPROVAL.
    approval = coord.request_confirmation(run_id, request, artifact)
    run = orch.get_run(run_id)
    ok_approval = run is not None and run.state == AgentRunState.WAITING_APPROVAL
    _record("B3·request_confirmation → WAITING_APPROVAL", ok_approval,
            f"state={run.state if run else 'MISSING'}")

    # Step 6: confirm_and_write — grants writable + EXECUTING.
    decision = coord.confirm_and_write(
        run_id, request, artifact, current_scene_revision=0,
    )
    ok_confirm = decision.writable and decision.artifact is not None
    _record("B3·confirm_and_write (writable=True)", ok_confirm,
            f"writable={decision.writable} reason={decision.reason!r}")

    # Step 7: complete_write → terminal.
    final = coord.complete_write(run_id, success=True)
    run = orch.get_run(run_id)
    events_final = [e.kind for e in orch.get_events(run_id)]
    ok_complete = (
        run is not None
        and run.state == AgentRunState.SUCCEEDED
        and AgentEventKind.RUN_COMPLETED in events_final
    )
    _record("B3·complete_write → SUCCEEDED", ok_complete,
            f"state={run.state if run else 'MISSING'}")


