# Test 4 (B4): Checkpoint persist / restore round-trip
# --------------------------------------------------------------------------- #


def test_b4_checkpoint_roundtrip(
    registry: ProfileRegistry, store: HybridCredentialStore
) -> None:
    _banner("测试 4 (B4) · Checkpoint 持久化 + 恢复 round-trip")

    # Run a real chat to create a genuine AgentRun.
    orch = AgentOrchestrator()
    active = registry.active_profile
    task = AgentTask(
        session_id="b4-test",
        title="checkpoint roundtrip",
        user_goal="测试持久化",
    )
    run_id = orch.start_task(task, mode="chat")
    orch.mark_context_ready(run_id)
    orch.mark_plan_ready(run_id)

    client = make_client(active, store)
    if client is None:
        _record("B4 checkpoint", False, "make_client 返回 None")
        return

    try:
        reply = client.complete(
            [{"role": "user", "content": "你好，一句话回答即可。"}],
            temperature=0.3, max_tokens=256,
        )
    except Exception as exc:  # noqa: BLE001
        _record("B4 checkpoint", False, f"模型调用失败: {exc}")
        return

    orch.begin_verification(run_id)
    orch.finish_verification(run_id, success=bool(reply and reply.strip()))

    run = orch.get_run(run_id)
    events = orch.get_events(run_id)
    assert run is not None, "run vanished"

    # Step 1: export state.
    state = orch.export_state()
    state_json = json.dumps(state, ensure_ascii=False)
    ok_export = "runs" in state and len(state.get("runs", [])) > 0
    _record("B4·export_state 含 run", ok_export,
            f"runs={len(state.get('runs', []))} JSON={len(state_json)} bytes")

    # Step 2: write to temp file (simulates ~/.topos/ai_assistant/v2_state.json).
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".json", delete=False, encoding="utf-8"
    ) as f:
        f.write(state_json)
        tmp_path = f.name

    try:
        # Step 3: read back and restore into a fresh orchestrator.
        with open(tmp_path, encoding="utf-8") as f:
            loaded = json.load(f)
        orch2 = AgentOrchestrator()
        count = orch2.restore_state(loaded)

        restored_run = orch2.get_run(run_id)
        restored_events = orch2.get_events(run_id)

        ok_restore = (
            count >= 1
            and restored_run is not None
            and restored_run.state == run.state
            and restored_run.task_id == run.task_id
        )
        detail = (
            f"restored={count} run "
            f"state={restored_run.state if restored_run else 'MISSING'} "
            f"(expected {run.state})"
        )
        _record("B4·restore_state 恢复 run", ok_restore, detail)

        # Step 4: simulate controller's "clear active_run_by_session" red-line.
        # The controller clears active sessions on restore so runs never
        # auto-regain active/approval status (security red-line 5).
        if "active_run_by_session" in loaded:
            loaded["active_run_by_session"] = {}
        orch3 = AgentOrchestrator()
        count3 = orch3.restore_state(loaded)
        ok_redline = count3 >= 1 and orch3.get_run(run_id) is not None
        _record("B4·清除 active session 后 run 仍在", ok_redline,
                f"runs restored={count3}")
    finally:
        os.unlink(tmp_path)


