# Test 3 (B6): History full-text storage (no 500-char truncation)
# --------------------------------------------------------------------------- #


def test_b6_history_full_text(
    registry: ProfileRegistry, store: HybridCredentialStore
) -> None:
    _banner("测试 3 (B6) · 历史完整正文存储（不再 500 字截断）")

    active = registry.active_profile
    client = make_client(active, store)
    if client is None:
        _record("B6 full-text", False, "make_client 返回 None")
        return

    # Request a reply that will exceed the old 500-char limit.
    prompt = "请写一段 800 字左右的短文，主题是「数字色彩与人类视觉感知的关系」，要有深度。"
    messages = [{"role": "user", "content": prompt}]
    try:
        reply = client.complete(messages, temperature=0.7, max_tokens=4096)
    except Exception as exc:  # noqa: BLE001
        _record("B6 full-text", False, f"模型调用失败: {exc}")
        return

    if not reply or not reply.strip():
        _record("B6 full-text", False, "模型返回空回复")
        return

    # Store through MessageRecord (B6 path).
    rec = MessageRecord(role="assistant", content=reply, run_id="b6-test")
    payload = rec.to_dict()
    stored_body = payload.get("content", "")
    content_complete = payload.get("content_complete", True)

    body, was_truncated = truncate_for_storage(reply)

    detail = (
        f"原文 {len(reply)} 字 → 存储 {len(stored_body)} 字 "
        f"| content_complete={content_complete} "
        f"| was_truncated={was_truncated} "
        f"| LIMIT={MESSAGE_CONTENT_LIMIT}"
    )

    ok = True
    if len(reply) > 500 and len(stored_body) <= 500:
        ok = False
        detail += " | ✗ 仍被截断到 500 字以内"
    if len(stored_body) < len(reply) and len(reply) <= MESSAGE_CONTENT_LIMIT:
        ok = False
        detail += f" | ✗ 未超限但正文缩短了 ({len(stored_body)} < {len(reply)})"
    if not content_complete and len(reply) <= MESSAGE_CONTENT_LIMIT:
        ok = False
        detail += " | ✗ content_complete=False 但正文未超限"

    _record("B6·长回复未截断", ok, detail)


