    task = AgentTask(
        task_id=f"media-{runtime_run_id}",
        session_id="media",
        title="AI TTS 生成",
        user_goal="",
        kind="text_to_speech",
    )
    v2_run_id = orch.start_task(task, mode="voice")
    orch.mark_context_ready(v2_run_id)
    orch.mark_plan_ready(v2_run_id)

    req = GenerationRequest(
        request_id=f"tts-{uuid.uuid4().hex[:8]}",
        modality=GenerationModality.VOICE,
        prompt="欢迎来到 Topos Color，这是一款专业的色彩校正与视频编辑工具。",
        consent=GenerationConsent(confirmed=True, provider_id=tts_profile.profile_id),
        budget=GenerationBudget(max_candidates=1),
    )
    t0 = time.perf_counter()
    try:
        result = provider.generate(req)
    except Exception as exc:  # noqa: BLE001
        orch.fail(v2_run_id, reason=str(exc))
        _record("B7·TTS 生成", False, f"{type(exc).__name__}: {exc}")
        return
    elapsed = time.perf_counter() - t0

    ok_gen = bool(result.candidates) and not result.error_code
    detail = f"{len(result.candidates)} 段 {elapsed:.1f}s"
    if result.candidates:
        handle = str(result.candidates[0].preview_handle)
        detail += f" | {len(handle)} chars handle"
        if os.path.exists(handle):
            detail += f" | file={os.path.getsize(handle)} bytes"
    _record("B7·Doubao TTS 生成", ok_gen, detail)

    if not ok_gen:
        orch.fail(v2_run_id, reason=result.error_code or "生成失败")
        return

    # B7: stage artifact + complete.
    from src.features.edit.ai_editing.agent_models import (
        ArtifactKind, ArtifactRef,
    )
    artifact = ArtifactRef(
        artifact_id=f"media-{runtime_run_id}",
        kind=ArtifactKind.AUDIO,
        location=str(result.candidates[0].preview_handle),
        created_at=time.time(),
    )
    orch.stage_artifact(v2_run_id, artifact)
    orch.begin_verification(v2_run_id)
    orch.finish_verification(v2_run_id, success=True)

    run = orch.get_run(v2_run_id)
    events = [e.kind for e in orch.get_events(v2_run_id)]
    ok_flow = (
        run is not None
        and run.state == AgentRunState.SUCCEEDED
        and AgentEventKind.ARTIFACT_STAGED in events
        and AgentEventKind.RUN_COMPLETED in events
    )
    _record("B7·TTS AgentRun (stage+complete)", ok_flow,
            f"state={run.state if run else 'MISSING'} events={len(events)}")


